def _mask(text: str) -> set[tuple[int, int]]:
    rows = (text[1:] if text.startswith("\n") else text).rstrip().split("\n")
    return {(x, y) for y, row in enumerate(rows) for x, c in enumerate(row) if c == "#"}


def lump(shape: str, slot: str, seed: int, grain: float = 0.25, cuts=(-0.1, 0.3, 0.62, 0.86)) -> st.Spr:
    return st.despeckle(st.shaded(_mask(shape), slot, cuts=cuts, grain=grain, seed=seed, cell=2.0))


PATCHES = (
    ((0, 0, 6), (1, 0, 5), (0, 1, 5), (1, 1, 4), (2, 1, 3)),
    ((0, 0, 6), (1, 0, 5), (2, 0, 4), (1, 1, 3)),
    ((0, 0, 6), (0, 1, 5), (1, 1, 4)),
    ((1, 0, 6), (0, 1, 6), (1, 1, 5), (2, 1, 4), (1, 2, 3)),
)


def spots(s: st.Spr, slot: str, where: list[tuple[int, int, int]]) -> st.Spr:
    """Metalleinschlüsse: unregelmäßige glänzende Flecken (oben links Glanz, unten rechts dunkler)."""
    for x, y, k in where:
        for dx, dy, lvl in PATCHES[k]:
            if s.opaque(x + dx, y + dy):
                s.set(x + dx, y + dy, (slot, lvl))
    return s


def raw_moonsilver() -> st.Spr:
    s = lump(CHUNK, "A", 501)
    return spots(s, "B", [(4, 5, 0), (10, 6, 1), (6, 9, 3), (11, 10, 2), (2, 9, 2)])


def raw_nightsteel() -> st.Spr:
    s = lump(CHUNK, "A", 502)
    return spots(s, "B", [(5, 5, 1), (10, 7, 0), (4, 10, 3), (11, 11, 2)])


def carbon() -> st.Spr:
    """Kohlenstoff: dunkler, kantiger Brocken mit bläulichen Bruchflächen."""
    s = lump(CHUNK, "A", 503, grain=0.35, cuts=(0.0, 0.35, 0.7, 0.9))
    for x, y in ((5, 5), (6, 5), (9, 7), (10, 7), (4, 9), (8, 10), (9, 10)):
        s.set(x, y, ("A", 6 if (x + y) % 3 else 5))
    return s


def steel_blend() -> st.Spr:
    """Stahlmischung: Haufen aus grauem Eisenpulver mit schwarzen Kohlenstoffkörnern."""
    s = lump(PILE, "A", 504, grain=0.3, cuts=(0.0, 0.35, 0.65, 0.88))
    for x, y in ((6, 8), (9, 9), (4, 11), (11, 11), (7, 12), (12, 13), (3, 12), (8, 10)):
        if s.opaque(x, y):
            s.set(x, y, ("B", 1 if (x * y) % 2 else 2))
    return s


