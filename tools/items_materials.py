def rune(kind: str) -> st.Spr:
    """Steintafel mit eingeschnittenem Zeichen: unter/rechts jedes Zeichenpixels eine dunkle Schnittkante."""
    s = st.Spr.art(RUNE_STONE)
    glyph = st.Spr.art(RUNE_GLYPHS[kind])
    for x, y, _ in glyph.cells():
        for dx, dy in ((1, 1), (0, 1), (1, 0)):
            p = s.get(x + dx, y + dy)
            if p is not None and p[0] == "A" and glyph.get(x + dx, y + dy) is None:
                s.set(x + dx, y + dy, ("A", 2 if (dx, dy) == (1, 1) else 3))
    return s.over(glyph)


def scale_ramp(kind: str) -> st.Ramp:
    scale = armor.DRAGONS[kind][0]
    return st.ramp(scale, dark=0.32 if kind == "ice" else 0.16, light=0.8 if kind == "lightning" else 0.93,
                   chroma_light=0.85, hue_light=45 if kind == "fire" else 22, chroma_dark=1.1)


SHARD_COLORS = {"fire": "#e0461a", "ice": "#8fd0f4", "lightning": "#e8c22a", "nature": "#4aae3a", "earth": "#b07a44",
                "water": "#2a8cd0"}


def shard_ramp(kind: str) -> st.Ramp:
    return st.ramp(SHARD_COLORS[kind], dark=0.2 if kind != "ice" else 0.34, light=0.97, chroma_light=0.75, hue_light=20)


def render(art: str | st.Spr, ramps: dict[str, st.Ramp], override: dict[str, str] | None = None,
           prefer: tuple[str, ...] = ("A", "B", "C", "D", "E")) -> Image.Image:
    s = st.Spr.art(art) if isinstance(art, str) else art
    return s.outline(prefer=prefer, override=override).image(ramps)


def build(put: Callable[[str, Image.Image], None]) -> None:
    put("item/steel_ingot", render(INGOT, {"A": STEEL}))
    put("item/nightsteel_ingot", render(NIGHTSTEEL_INGOT, {"A": NIGHT, "B": MOONSILVER}, override={"B": "A"}))
    put("item/abyssite_ingot", render(ABYSSITE_INGOT, {"A": ABYSS, "D": ABYSS_GLOW}, override={"D": "A"}))
    put("item/moonsilver_ingot", render(MOONSILVER_INGOT, {"A": MOONSILVER, "E": MOON_TINT}, override={"E": "A"}))
    put("item/moonsilver_nugget", render(NUGGET, {"A": MOONSILVER}))
    put("item/raw_moonsilver", render(raw_moonsilver(), {"A": RAW_ROCK_PALE, "B": MOONSILVER}, prefer=("A",)))
    put("item/raw_nightsteel", render(raw_nightsteel(), {"A": RAW_ROCK_DARK, "B": NIGHT}, prefer=("A",)))
    put("item/carbon", render(carbon(), {"A": CARBON}))
    put("item/steel_blend", render(steel_blend(), {"A": STEEL_POWDER, "B": CARBON}, prefer=("A",)))

    put("item/konterit", render(KONTERIT_GEM, {"A": KONTERIT}))
    put("item/aetherit", render(AETHERIT_GEM, {"A": AETHERIT}))
    put("item/draconium", render(DRACONIUM_GEM, {"A": DRACONIUM, "D": gear.EMBER}, override={"D": "A"}))
    put("item/wyvernit", render(WYVERNIT_GEM, {"A": WYVERNIT}))
    put("item/gemstone", render(GEMSTONE_GEM, {"A": GEM_VIOLET, "B": GEM_GREEN}))
    put("item/night_crystal_shard", render(NIGHT_SHARD, {"A": NIGHT_CRYSTAL, "D": SOUL}, override={"D": "A"}))
    put("item/soul_crystal", render(SOUL_CRYSTAL, {"A": SOUL, "D": SOUL}))
    put("item/abyssite_shard", render(ABYSSITE_SHARD, {"A": ABYSS, "D": ABYSS_GLOW}, override={"D": "A"}))
    put("item/shadow_essence", render(SHADOW_ESSENCE, {"A": SHADOW}))
