def lantern_block() -> tuple[Image.Image, Image.Image]:
    """Die Blocktextur in der Aufteilung der Vanilla-Laterne (eigene Pixel): Gehäuseseiten (0..5, 2..8), Boden/Deckel
    (0..5, 9..14), Deckelrand (1..4, 0..1) und -oben (1..4, 10..13), Bügel und Kette (11..13, 1..11)."""
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    glow = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    px, gp = img.load(), glow.load()
    frame = PRISMARINE
    iron = IRON
    lure = LURE
    # Gehäuseseiten: Rahmen aus Prismarin, dazwischen Glas mit dem leuchtenden Köder
    for y in range(2, 9):
        for x in range(0, 6):
            edge = x in (0, 5) or y in (2, 8)
            if edge:
                px[x, y] = frame[2] if (x == 0 or y == 2) else frame[1]
            else:
                d = abs(x - 2.5) + abs(y - 5.2) * 0.8
                col = lure[6] if d < 1.0 else lure[5] if d < 1.8 else lure[3]
                px[x, y] = col
                gp[x, y] = col
    for x in (0, 5):
        px[x, 2] = iron[4]
        px[x, 8] = iron[2]
    # Boden und Deckel des Gehäuses (6x6), in der Mitte der Deckel des Aufsatzes (4x4)
    for y in range(9, 15):
        for x in range(0, 6):
            edge = x in (0, 5) or y in (9, 14)
            px[x, y] = frame[1] if edge else frame[3] if (x + y) % 2 else frame[2]
    for y in range(10, 14):
        for x in range(1, 5):
            px[x, y] = iron[3] if (x in (1, 4) or y in (10, 13)) else iron[4]
    # Rand des Aufsatzes (4x2)
    for x in range(1, 5):
        px[x, 0] = iron[4]
        px[x, 1] = iron[2]
    # Bügel und Kette: Glieder aus dunklem Eisen
    for y in range(1, 12):
        for x in range(11, 14):
            link = (y % 3 != 0) and x != 12 or (y % 3 == 0 and x == 12)
            if link:
                px[x, y] = iron[3] if x == 11 else iron[1]
    return img, glow


def build(put: Callable[[str, Image.Image], None]) -> None:
    put("item/glow_jelly", render(GLOW_JELLY, {"A": JELLY, "C": JELLY_CORE}))
    put("item/angler_lure", render(ANGLER_LURE, {"A": LURE, "B": STALK}, prefer=("A", "B")))
    put("item/shark_tooth", render(SHARK_TOOTH, {"A": TOOTH, "B": ROOT}))
    put("item/crab_claw", render(CRAB_CLAW, {"A": SHELL, "C": TIP}))
    put("item/crab_meat", render(CRAB_MEAT, {"A": MEAT, "C": MEAT_RED}))
    put("item/cooked_crab_meat", render(COOKED_CRAB_MEAT, {"A": COOKED, "C": MEAT}, prefer=("A", "C")))
    bucket = st.Spr.art(BUCKET, legend={"h": ("C", 3)}).over(st.Spr.art(JELLY_IN_BUCKET))
    put("item/glow_jellyfish_bucket", render(bucket, {"A": IRON, "B": IRON, "C": WATER, "D": JELLY}, prefer=("A", "B")))
    put("item/deep_sea_lantern", render(LANTERN_ITEM, {"A": PRISMARINE, "B": IRON, "C": LURE}, prefer=("A", "B")))
    block, block_glow = lantern_block()
    put("block/deep_sea_lantern", block)
