def dusk_bread() -> st.Spr:
    s = st.shaded(_mask(DUSK_BREAD_BODY), "A", cuts=(-0.05, 0.35, 0.68, 0.9), grain=0.1, seed=31)
    # schräge Einschnitte (hell im Schnitt, dunkle Kante darunter)
    for (x, y) in ((11, 6), (10, 7), (8, 7), (7, 8), (5, 8), (4, 9)):
        s.set(x, y, ("A", 6))
        if s.opaque(x, y + 1):
            s.set(x, y + 1, ("A", 3))
    for x, y in ((12, 8), (9, 10), (6, 11), (3, 11), (9, 8)):
        if s.opaque(x, y):
            s.set(x, y, ("D", 5))
    return s


