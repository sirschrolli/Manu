def cabbage() -> st.Spr:
    s = st.shaded(_mask(CABBAGE_HEAD), "A", cuts=(0.0, 0.4, 0.72, 0.9), grain=0.12, seed=7, cell=2.0)
    detail = st.Spr.art(CABBAGE_DETAIL, legend={"+": ("X", 1), "-": ("X", -1)})
    for x, y, px in detail.cells():
        if px[0] == "X":
            cur = s.get(x, y)
            if cur:
                s.set(x, y, ("A", st.clamp(cur[1] + 2 * px[1], 2, 6)))
        else:
            s.set(x, y, px)
    return s


