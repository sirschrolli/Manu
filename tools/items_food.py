def render(art: str | st.Spr, ramps: dict[str, st.Ramp], prefer: tuple[str, ...] = ("A", "B", "C", "D", "E"),
           override: dict[str, str] | None = None) -> Image.Image:
    s = st.Spr.art(art) if isinstance(art, str) else art
    return s.outline(prefer=prefer, override=override).image(ramps)


def build(put: Callable[[str, Image.Image], None]) -> None:
    put("item/cabbage", render(cabbage(), {"A": CABBAGE, "B": CABBAGE_OUTER}, prefer=("B", "A")))
    put("item/tomato", render(tomato(), {"A": TOMATO, "C": LEAF}))
    berries = st.Spr.art(SOUL_BERRIES).outline(slots=("A", "D"), override={"D": "A"})
    put("item/soul_berries", berries.image({"A": SOUL, "C": SOUL_STEM, "D": SOUL}))
    put("item/duskgrain", grain_bundle().image({"A": DUSK, "D": DUSK_GLOW}))
    put("item/dusk_bread", render(dusk_bread(), {"A": DUSK_CRUST, "D": DUSK_GLOW}, override={"D": "A"}))
    # Saatgut ohne Umriss (wie bei Vanilla): jedes Korn hat seinen eigenen dunklen Fuß
    put("item/barley_seeds", st.Spr.art(SEEDS_LONG).image({"A": SEED_BARLEY}))
    put("item/duskgrain_seeds", st.Spr.art(SEEDS_LONG).image({"A": SEED_DUSK}))
    put("item/cabbage_seeds", st.Spr.art(SEEDS_ROUND).image({"A": SEED_CABBAGE}))
    put("item/tomato_seeds", st.Spr.art(SEEDS_FLAT).image({"A": SEED_TOMATO}))


