def _box(img: Image.Image, u: int, v: int, w: int, h: int, d: int, color_at: Callable[[int, int, str], tuple]) -> None:
    """Füllt die Kastenabwicklung eines Quaders (oben, unten, Seiten) – color_at bekommt Pixel und Seite."""
    px = img.load()
    faces = {
        "top": (u + d, v, w, d), "bottom": (u + d + w, v, w, d),
        "east": (u, v + d, d, h), "north": (u + d, v + d, w, h), "west": (u + d + w, v + d, d, h), "south": (u + 2 * d + w, v + d, w, h),
    }
    for face, (x0, y0, fw, fh) in faces.items():
        for y in range(y0, y0 + fh):
            for x in range(x0, x0 + fw):
                if 0 <= x < img.width and 0 <= y < img.height:
                    px[x, y] = color_at(x - x0, y - y0, face)


def pelt_parts() -> Image.Image:
    img = Image.new("RGBA", (64, 32), (0, 0, 0, 0))
    rnd = st.seeded(70)

    def fur(x: int, y: int, face: str):
        v = 3 + (1 if (x * 5 + y * 3) % 7 == 0 else 0) - (1 if rnd.random() < 0.18 else 0)
        if face == "top":
            v += 1
        if face == "bottom":
            v -= 1
        return FUR[max(1, min(6, v))]

    def ear(x: int, y: int, face: str):
        if face == "north" and 0 < x < 2 and y > 0:
            return st.hexc("#8a5a52")                                    # das Innere des Ohrs
        return fur(x, y, face)

    _box(img, 0, 0, 3, 3, 1, ear)
    _box(img, 8, 0, 3, 3, 1, ear)
    _box(img, 16, 0, 1, 1, 1, lambda x, y, f: BONE[6])
    _box(img, 20, 0, 1, 1, 1, lambda x, y, f: BONE[6])

    def snout(x: int, y: int, face: str):
        if face == "north":
            return FUR[2] if y < 2 else LEATHER[1]                          # die Lefzen vorn dunkel
        if face == "bottom":
            return st.hexc("#5a2a28")                                       # der Gaumen
        return fur(x, y, face)

    _box(img, 0, 4, 4, 3, 4, snout)
    _box(img, 16, 4, 2, 1, 1, lambda x, y, f: st.hexc("#151112"))
    _box(img, 0, 12, 10, 3, 6, fur)
    _box(img, 32, 0, 5, 3, 5, fur)
    _box(img, 32, 8, 5, 3, 5, fur)
    return img


def ember_parts() -> tuple[Image.Image, Image.Image]:
    img = Image.new("RGBA", (64, 32), (0, 0, 0, 0))
    glow = Image.new("RGBA", (64, 32), (0, 0, 0, 0))

    def horn(level: int, hot: bool):
        def at(x: int, y: int, face: str):
            if hot:
                return EMBER[5 if y == 0 else 4]
            ridge = (y % 2 == 0)
            return BASALT[level + (1 if ridge else 0)]
        return at

    for v in (0, 5):
        _box(img, 0, v, 2, 3, 2, horn(2, False))
        _box(img, 8, v, 1, 2, 1, horn(3, False))       # 1.5er Glied: Abwicklung mit ganzen Pixeln
        _box(img, 14, v, 1, 2, 1, horn(0, True))
        _box(glow, 14, v, 1, 2, 1, horn(0, True))
    _box(img, 24, 0, 2, 1, 8, lambda x, y, f: EMBER[4] if f == "top" and x == 0 else BASALT[3 + (y % 2)])
    _box(glow, 24, 0, 2, 1, 8, lambda x, y, f: EMBER[4] if f == "top" and x == 0 else (0, 0, 0, 0))
    for i in range(3):
        _box(img, 0, 12 + i * 5, 2, 2, 2, lambda x, y, f: BASALT[3 if (x + y) % 2 else 2])
        _box(img, 8, 12 + i * 5, 1, 1, 2, lambda x, y, f: EMBER[5])
        _box(glow, 8, 12 + i * 5, 1, 1, 2, lambda x, y, f: EMBER[5])
    return img, glow


