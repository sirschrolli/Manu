    _fill(img, 2, 0, 4, 16, lambda x, y: ASH[3] if y % 3 == 0 else ASH[5 if x % 4 < 2 else 4])
    _fill(img, 4, 0, 6, 16, lambda x, y: BONE[5 if (x + y) % 4 else 4])

