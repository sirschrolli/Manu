def _mask(text: str, chars: str) -> set[tuple[int, int]]:
    return {(x, y) for y, row in enumerate(text.strip("\n").split("\n")) for x, c in enumerate(row) if c in chars}


def base(shape: str, slot: str = "A") -> st.Spr:
    """Gewölbt schattierte Grundform; die Innenseite eines offenen Helms ist dunkel."""
    s = st.shaded(_mask(shape, "#"), slot, cuts=(-0.05, 0.4, 0.75, 0.93), radius=1.6)
    for p in _mask(shape, "%"):
        s.set(p[0], p[1], (slot, 1))
    return s


def scale_pattern(s: st.Spr, slot: str = "A", region: set[tuple[int, int]] | None = None) -> st.Spr:
    """Schuppen: Gitter aus 3x2-Zellen, oben Mitte heller, unten links/rechts dunkler, jede zweite Reihe versetzt."""
    pattern = ((0, 1, 0), (-1, 0, -1))
    for x, y, (sl, lv) in list(s.cells()):
        if sl != slot or lv <= 1 or (region is not None and (x, y) not in region):
            continue
        row = y // 2
        u = (x + (row % 2)) % 3
        s.set(x, y, (sl, st.clamp(lv + pattern[y % 2][u], 2, 6)))
    return s


def finish(s: st.Spr, overlay: str | None, ramps: dict[str, st.Ramp], prefer: tuple[str, ...] = ("A", "B", "C", "D", "E"),
           override: dict[str, str] | None = None) -> Image.Image:
    if overlay:
        s.over(st.Spr.art(overlay))
    return s.outline(prefer=prefer, override=override).image(ramps)


