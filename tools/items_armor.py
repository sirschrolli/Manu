def build(put: Callable[[str, Image.Image], None]) -> None:
    pieces = (("helmet", None), ("chestplate", CHESTPLATE), ("leggings", LEGGINGS), ("boots", BOOTS))

    def plate(name: str, ramps: dict[str, st.Ramp], overlays: tuple[str, str, str, str], helmet: str,
              override: dict[str, str] | None = None) -> None:
        for (piece, shape), overlay in zip(pieces, overlays):
            s = base(shape or helmet)
            put(f"item/{name}_{piece}", finish(s, overlay, ramps, override=override))

    plate("steel", {"A": gear.STEEL, "B": gear.BRASS},
          (STEEL_HELMET, STEEL_CHEST, STEEL_LEGS, STEEL_BOOTS), CLOSED_HELMET)
    plate("nightsteel", {"A": gear.NIGHT, "B": gear.MOONSILVER, "E": gear.NIGHT_GEM},
          (NIGHT_HELMET, NIGHT_CHEST, NIGHT_LEGS, NIGHT_BOOTS), OPEN_HELMET)
    plate("abyssite", {"A": gear.ABYSS, "D": gear.ABYSS_GLOW},
          (ABYSS_HELMET, ABYSS_CHEST, ABYSS_LEGS, ABYSS_BOOTS), CLOSED_HELMET, override={"D": "A"})
    plate("konterit", {"A": KONTERIT, "B": gear.STEEL_DARK, "D": KONTERIT_GLOW},
          (KONTERIT_HELMET, KONTERIT_CHEST, KONTERIT_LEGS, KONTERIT_BOOTS), CLOSED_HELMET, override={"D": "A"})

    plate("moonstone", {"A": MOON_PLATE, "B": gear.MOONSILVER, "D": MOON_GLOW, "E": MOON_GEM},
          (MOON_HELMET, MOON_CHEST, MOON_LEGS, MOON_BOOTS), OPEN_HELMET, override={"D": "A", "E": "B"})

    aquamarine_icons(put)

    for kind in DRAGONS:
        ramps = dragon_ramps(kind)
        for (piece, shape), overlay in zip(pieces, (DRAGON_HELMET, DRAGON_CHEST, DRAGON_LEGS, DRAGON_BOOTS)):
            s = scale_pattern(base(shape or OPEN_HELMET))
            put(f"item/{kind}_dragon_scale_{piece}", finish(s, overlay, ramps, prefer=("A", "C", "B", "D")))


