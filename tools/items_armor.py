def dragon_ramps(kind: str) -> dict[str, st.Ramp]:
    scale, belly, horn, accent = DRAGONS[kind]
    light = 0.95 if kind == "ice" else 0.88
    return {
        "A": st.ramp(scale, dark=0.16 if kind != "ice" else 0.3, light=light, chroma_light=0.6),
        "B": st.ramp(belly, dark=0.25, light=0.96, chroma_light=0.5),
        "C": st.ramp(horn, dark=0.18, light=0.97, chroma_light=0.5),
        "D": st.ramp(accent, dark=0.3, light=0.98, chroma_light=0.5),
    }


