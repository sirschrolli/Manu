def render(art: str, ramps: dict[str, st.Ramp], prefer: tuple[str, ...] = ("A", "B", "D", "C"),
           override: dict[str, str] | None = None) -> Image.Image:
    return st.Spr.art(art).outline(prefer=prefer, override=override).image(ramps)


def build(put: Callable[[str, Image.Image], None]) -> None:
    steel_tool = {"A": STEEL, "B": STEEL_DARK, "C": OAK}
    put("item/steel_sword", render(STEEL_SWORD, {"A": STEEL, "B": BRASS, "C": LEATHER}))
    put("item/steel_pickaxe", render(STEEL_PICKAXE, steel_tool))
    put("item/steel_axe", render(STEEL_AXE, steel_tool))
    put("item/steel_shovel", render(STEEL_SHOVEL, steel_tool))
    put("item/steel_hoe", render(STEEL_HOE, steel_tool))

    night = {"A": NIGHT, "B": MOONSILVER, "C": DUSKWOOD, "D": MOONSILVER}
    put("item/nightsteel_sword", render(NIGHT_SWORD, {**night, "E": NIGHT_GEM}))
    put("item/nightsteel_pickaxe", render(NIGHT_PICKAXE, night))
    put("item/nightsteel_axe", render(NIGHT_AXE, night))
    put("item/nightsteel_shovel", render(NIGHT_SHOVEL, night))
    put("item/nightsteel_hoe", render(NIGHT_HOE, night))

    abyss = {"A": ABYSS, "B": ABYSS, "C": ABYSS_GRIP, "D": ABYSS_GLOW}
    put("item/abyssite_sword", render(ABYSS_SWORD, abyss, override={"D": "A"}))
    put("item/abyssite_pickaxe", render(ABYSS_PICKAXE, abyss, override={"D": "A"}))
    put("item/abyssite_axe", render(ABYSS_AXE, abyss, override={"D": "A"}))
    put("item/abyssite_shovel", render(ABYSS_SHOVEL, abyss, override={"D": "A"}))
    put("item/abyssite_hoe", render(ABYSS_HOE, abyss, override={"D": "A"}))

    put("item/draconium_sword", render(DRACONIUM_SWORD, {"A": DRACONIUM, "B": DRAGON_GOLD, "C": DRAGON_LEATHER,
                                                       "D": EMBER, "E": EMBER}))
    put("item/draconium_axe", render(DRACONIUM_AXE, {"A": DRACONIUM, "B": DRAGON_GOLD, "C": DRAGON_LEATHER, "D": EMBER}))
    put("item/moonsilver_blade", render(MOONSILVER_BLADE, {"A": MOONSILVER, "B": MOONSILVER, "C": DUSKWOOD,
                                                         "D": MOON_GRIP, "E": MOON_GLOW}))
    put("item/aetherit_staff", render(AETHERIT_STAFF, {"A": AETHERIT, "B": MOONSILVER, "C": DUSKWOOD, "D": AETHERIT}))


if __name__ == "__main__":
    import sys

    sheet: dict[str, Image.Image] = {}
    build(lambda key, img: sheet.__setitem__(key.split("/")[-1], img))
    st.preview(sheet, sys.argv[1] if len(sys.argv) > 1 else "items_gear.png", zoom=8, cols=5)
