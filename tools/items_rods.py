def sprite(art: str, overlay: str | None = None, keep: str | None = None) -> st.Spr:
    s = st.Spr.art(art)
    if overlay:
        s.draw(overlay)
    # der Haken bleibt fein (ohne Umriss), wie die Schnur
    s = s.outline(slots=("A", "B", "C", "F", "G"), prefer=("C", "F", "G", "A", "B"))
    if keep:
        # nach dem Umriss: Pixel, die selbst leuchten oder funkeln (ohne dunklen Rand)
        s.draw(keep)
    return s


def line(*hex_values: str) -> list:
    return st.fixed(*hex_values)


