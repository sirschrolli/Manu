def _mask(text: str) -> set[tuple[int, int]]:
    rows = (text[1:] if text.startswith("\n") else text).rstrip().split("\n")
    return {(x, y) for y, row in enumerate(rows) for x, c in enumerate(row) if c == "#"}


EGG_MASK = _mask(EGG)


class Egg:
    """Ei mit gewölbter Grundschattierung; paint() malt relativ, draw() absolut."""

    def __init__(self, cuts: tuple[float, ...] = (0.05, 0.42, 0.74, 0.93)):
        self.spr = st.shaded(EGG_MASK, "A", cuts=cuts)
        self.dome = {(x, y): px[1] for x, y, px in self.spr.cells()}

    def paint(self, art: str, legend: dict[str, tuple[str, int]]) -> "Egg":
        """Zeichen -> (Slot, Versatz zur Wölbungsstufe). Nur innerhalb des Eis."""
        rows = (art[1:] if art.startswith("\n") else art).rstrip().split("\n")
        for y, row in enumerate(rows):
            for x, ch in enumerate(row):
                if ch in legend and (x, y) in self.dome:
                    slot, delta = legend[ch]
                    self.spr.set(x, y, (slot, st.clamp(self.dome[(x, y)] + delta, 1, 6)))
        return self

    def draw(self, art: str, legend: dict[str, st.Px] | None = None) -> "Egg":
        self.spr.draw(art, legend=legend)
        return self

    def image(self, ramps: dict[str, st.Ramp], prefer: tuple[str, ...] = ("A", "B", "C", "D", "E", "F", "G"),
              override: dict[str, str] | None = None) -> Image.Image:
        return self.spr.outline(prefer=prefer, override=override).image(ramps)


def R(base: str, dark: float = 0.2, light: float = 0.92, **kw) -> st.Ramp:
    return st.ramp(base, dark=dark, light=light, **kw)


# Häufige relative Zeichen: x = Slot B gleich hell, y = B eine Stufe dunkler, z = C, w = D, v = E, u = F
REL = {
    "x": ("B", 0), "y": ("B", -1), "Y": ("B", 1),
    "z": ("C", 0), "Z": ("C", -1), "Q": ("C", 1),
    "w": ("D", 0), "W": ("D", -1),
    "v": ("E", 0), "V": ("E", -1),
    "u": ("F", 0),
    "-": ("A", -1), "=": ("A", -2), "+": ("A", 1),
}

# Absolute Zeichen für Augen, Glanz usw. (Slot G = Augen/Leuchten)
EYE = {"@": ("G", 1), "*": ("G", 6), "&": ("G", 4), "%": ("G", 3)}


